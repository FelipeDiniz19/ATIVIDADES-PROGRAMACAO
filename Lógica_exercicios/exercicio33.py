print ("---------------DIA DA SEMANA---------------")


n1 = int(input("Digite o numero e veja qual dia da semana: "))

if n1 == 1:
    print("SEGUNDA-FEIRA")

elif n1 == 2:
    print("TERCA-FEIRA")

elif n1 == 3:
    print("QUARTA-FEIRA")

elif n1 == 4:
    print("QUINTA-FEIRA")

elif n1 == 5:
    print("SEXTA-FEIRA")

elif n1 == 6:
    print("SABADO")

elif n1 == 7:
    print("DOMINGO")

else:
    print("OPCAO INVALIDA")