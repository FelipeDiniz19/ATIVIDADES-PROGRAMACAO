def somar(numero1, numero2):
    resultado = numero1 + numero2
    return resultado



def subtrair(numero1, numero2):
    resultado = numero1 - numero2
    return resultado


def  dividir(numero1, numero2):
    resultado = numero1 / numero2
    return resultado


def multiplicar(numero1, numero2):
    resultado = numero1 * numero2
    return resultado



print(f"Soma 5+5,{somar(5,5)}")
print(f"Subtraia 5-5,{subtrair(5,5)}")
print(f"Divida 5/5,{dividir(5,5)}")
print(f"Multiplique 5x5, {multiplicar(5,5)}")


